/**
 * Evidence capture entry point (port of `scripts/capture_cli_evidence.py`'s `main()`), run by
 * `scripts/capture-cli-evidence.mjs` through `scripts/capture-cli-evidence.vitest.config.mjs`. It is not part of the
 * default test run (the file name does not match `*.test.ts`).
 *
 * Executes every registered evidence case (offline, mocked backend) and writes the Markdown evidence documents.
 * Options arrive as JSON in `ABX_CAPTURE_OPTIONS`: `{ out, command, live }`.
 */

import "../_support/isolatedHome.js";

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { beforeEach, it } from "vitest";

import { _CI_ENV_VARS } from "../_support/env.js";
import { delenv } from "../helpers/templateSupport.js";
import { REGISTRY, runCase, type EvidenceCase } from "./evidence_cases.js";

interface CaptureOptions {
  out: string;
  command: string | null;
  live: boolean;
}

const PROJECT_ROOT = fileURLToPath(new URL("../../", import.meta.url));
const options: CaptureOptions = {
  out: path.join(PROJECT_ROOT, ".agents", "evidence"),
  command: null,
  live: false,
  ...(JSON.parse(process.env["ABX_CAPTURE_OPTIONS"] ?? "{}") as Partial<CaptureOptions>),
};

const GENERATED_HEADER = "<!-- ⚠️  AUTO-GENERATED by scripts/capture-cli-evidence.mjs — DO NOT EDIT -->\n\n";

/** Pretty-print a command list for a Markdown fenced block. */
function cmdDisplay(cmd: string[]): string {
  const parts = cmd.map((c) => (c === "" || c.includes(" ") || /['"]/.test(c) ? `"${c}"` : c));
  return `abx ${parts.join(" ")}`;
}

function caseToMarkdown(testCase: EvidenceCase, stdout: string, stderr: string, exitCode: number): string {
  const lines = [`### ${testCase.description}\n`];
  lines.push("```");
  lines.push(`$ ${cmdDisplay(testCase.command)}`);
  if (stdout.trim()) lines.push(stdout.replace(/\s+$/, ""));
  lines.push(`Exit code: ${exitCode}`);
  lines.push("```");
  if (stderr.trim()) {
    lines.push("\n**stderr:**\n");
    lines.push("```");
    lines.push(stderr.replace(/\s+$/, ""));
    lines.push("```");
  }
  lines.push("");
  return lines.join("\n");
}

/** Doc-group key derived from the output file name. */
const groupKey = (outputFile: string): string => outputFile.split("-")[0]!;

const DOC_SUBDIR_MAP: Record<string, string> = { config: "cli/config", template: "cli/template", mcp: "cli/mcp" };

/** Python `str.title()` for the ASCII group names used here. */
const pyTitle = (text: string): string => text.replace(/[A-Za-z]+/g, (w) => w[0]!.toUpperCase() + w.slice(1).toLowerCase());

beforeEach(() => {
  for (const v of _CI_ENV_VARS) delenv(v);
});

it("capture CLI evidence", async () => {
  const liveAvailable = Boolean(process.env["E2B_API_KEY"]);
  const groups = new Map<string, string[]>();
  let total = 0;
  let skipped = 0;

  for (const testCase of REGISTRY) {
    if (options.command && !testCase.output_file.startsWith(options.command)) continue;
    total++;
    if (testCase.category === "B" && testCase.mock_setup === null && !(options.live && liveAvailable)) {
      skipped++;
      continue;
    }
    const { stdout, stderr, exit_code } = await runCase(testCase);
    const gk = groupKey(testCase.output_file);
    groups.set(gk, [...(groups.get(gk) ?? []), caseToMarkdown(testCase, stdout, stderr, exit_code)]);
  }

  const docsBase = path.resolve(options.out);
  for (const subdir of ["cli", "cli/config", "cli/template", "cli/mcp"]) fs.mkdirSync(path.join(docsBase, subdir), { recursive: true });

  let filesWritten = 0;
  const sortedKeys = [...groups.keys()].sort();
  for (const gk of sortedKeys) {
    const subdir = DOC_SUBDIR_MAP[gk] ?? "cli";
    const outPath = path.join(docsBase, subdir, `${gk}.md`);
    const content = `${GENERATED_HEADER}# CLI Evidence: ${pyTitle(gk.replace(/-/g, " "))}\n\n${groups.get(gk)!.join("\n")}`;
    fs.writeFileSync(outPath, content);
    filesWritten++;
    process.stdout.write(`  wrote ${path.relative(docsBase, outPath)}\n`);
  }

  let readme = GENERATED_HEADER;
  readme += "# CLI Evidence Documentation\n\n";
  readme +=
    "This directory contains auto-generated evidence of every CLI command's\n" +
    "input→output behaviour. Each Markdown file shows the exact command invoked,\n" +
    "its stdout, exit code, and stderr (when non-empty).\n\n";
  readme += "## Regenerate\n\n";
  readme += "```bash\n";
  readme += "# Offline (mocked backend) — default\n";
  readme += "node scripts/capture-cli-evidence.mjs\n\n";
  readme += "# With real backend (configure ABX_SANDBOX_API_KEY and its endpoint first)\n";
  readme += "node scripts/capture-cli-evidence.mjs --live\n\n";
  readme += "# Single command group\n";
  readme += "node scripts/capture-cli-evidence.mjs --command create\n";
  readme += "```\n\n";
  readme += "## Files\n\n";
  for (const gk of sortedKeys) {
    const subdir = DOC_SUBDIR_MAP[gk] ?? "cli";
    readme += `- [\`${subdir}/${gk}.md\`](${subdir}/${gk}.md)\n`;
  }
  readme += `\n**Total cases:** ${total - skipped} run, ${skipped} skipped\n`;
  // A hand-curated README.md (no generated header) is never overwritten; the generated index goes next to it.
  const readmePath = path.join(docsBase, "README.md");
  const curated = fs.existsSync(readmePath) && !fs.readFileSync(readmePath, "utf8").startsWith(GENERATED_HEADER.trimEnd());
  fs.writeFileSync(curated ? path.join(docsBase, "README.generated.md") : readmePath, readme);
  filesWritten++;
  process.stdout.write(`\nDone: ${total - skipped} cases run, ${skipped} skipped, ${filesWritten} files written.\n`);
}, 120_000);
