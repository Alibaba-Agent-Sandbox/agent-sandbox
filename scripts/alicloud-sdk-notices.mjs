/** Regenerate attribution for the official Express SDK's bundled dependency graph. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = path.join(root, "src/licenses/runtime_dependencies.ts");
const bundle = await build({
  absWorkingDir: root,
  entryPoints: ["src/providers/alicloud_express/sdk.ts"],
  bundle: true,
  platform: "node",
  format: "cjs",
  write: false,
  metafile: true,
  define: { "import.meta.url": '"file:///bundled-sdk.cjs"' },
  logLevel: "silent",
});
const directories = new Set();
for (const input of Object.keys(bundle.metafile.inputs)) {
  if (!input.includes("node_modules/")) continue;
  let directory = path.dirname(path.resolve(root, input));
  while (!fs.existsSync(path.join(directory, "package.json"))) directory = path.dirname(directory);
  directories.add(directory);
}
const packages = [...directories].map(directory => ({ directory, metadata: JSON.parse(fs.readFileSync(path.join(directory, "package.json"), "utf8")) }))
  .sort((a, b) => a.metadata.name.localeCompare(b.metadata.name, "en"));
let text = "\nExpress official SDK dependency attribution\n" +
  "Scope: the dependency graph embedded by the official SDK loaders; this is not a complete CLI SBOM.\n" +
  "The package metadata and shipped license/README notices below are retained as provided, including upstream inconsistencies.\n" +
  "Packages without a shipped license text retain their declared license and available README notice.\n" +
  "Apache License 2.0 full text follows the package notices.\n";
for (const { directory, metadata } of packages) {
  text += `\n--- ${metadata.name}@${metadata.version} (package metadata: ${metadata.license ?? "unspecified"}) ---\n`;
  const notices = fs.readdirSync(directory).filter(name => /^(licen[sc]e|copying|notice)/i.test(name) && fs.statSync(path.join(directory, name)).isFile()).sort();
  for (const name of notices) text += `${name}:\n${fs.readFileSync(path.join(directory, name), "utf8").replaceAll("\r\n", "\n")}\n`;
  const readme = fs.readdirSync(directory).find(name => /^readme\.md$/i.test(name));
  if (readme) {
    const content = fs.readFileSync(path.join(directory, readme), "utf8");
    const start = content.search(/^#{1,6}\s+Licen[sc]e\b/im);
    if (start >= 0) {
      const section = content.slice(start).split(/\n#{1,6}\s+/)[0];
      text += `${readme} notice:\n${section}\n`;
    }
  }
}
text += "\n--- Apache License 2.0 ---\n" + fs.readFileSync(path.join(root, "LICENSE"), "utf8");
text = text.replace(/\r\n?/g, "\n");
const generated = "// Generated by node scripts/alicloud-sdk-notices.mjs; do not edit by hand.\n" +
  "export const RUNTIME_DEPENDENCY_NOTICES = " + JSON.stringify(text) + ";\n";
if (process.argv.includes("--check")) {
  if (fs.readFileSync(output, "utf8") !== generated) throw new Error("Express SDK notices are stale; run node scripts/alicloud-sdk-notices.mjs");
} else {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, generated);
}
console.log(`Express SDK attribution: ${packages.length} packages${process.argv.includes("--check") ? " verified" : " recorded"}.`);
