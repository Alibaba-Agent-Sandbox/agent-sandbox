function unlinkIfExists(file: string): void {
  try {
    fs.unlinkSync(file);
  } catch (exc) {
    if ((exc as NodeJS.ErrnoException).code !== "ENOENT") throw exc;
  }
}

function isRelativeTo(child: string, parent: string): boolean {
  const relative = path.relative(parent, child);
  return relative !== "" && !relative.startsWith("..") && !path.isAbsolute(relative);
}

function rel(root: string, file: string): string {
  return path.relative(root, file).split(path.sep).join("/");
}

function sha256(file: string): string {
  return createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

function exclude(bucket: Record<string, string[]>, reason: string, relative: string): void {
  (bucket[reason] ??= []).push(relative);
}

function isSecretName(name: string): boolean {
  const lower = name.toLowerCase();
  if (lower === ".env") return true;
  if (lower.startsWith(".env.") && ![".example", ".sample", ".template"].some((s) => lower.endsWith(s))) return true;
  if ([".pem", ".key", ".p12", ".pfx", ".tfvars"].some((s) => lower.endsWith(s)) || lower.includes(".tfstate")) {
    return true;
  }
  if (["kubeconfig", "id_rsa", "id_ed25519", "credentials"].some((s) => lower.startsWith(s))) return true;
  if ([".npmrc", ".pypirc", ".netrc", ".git-credentials"].includes(lower)) return true;
  return lower === "secrets" || lower.startsWith("secrets.");
}

function readHead(file: string, limit: number): Buffer {
  const fd = fs.openSync(file, "r");
  try {
    const buffer = Buffer.alloc(limit);
    let filled = 0;
    while (filled < limit) {
      const n = fs.readSync(fd, buffer, filled, limit - filled, null);
      if (n === 0) break;
      filled += n;
    }
    return buffer.subarray(0, filled);
  } finally {
    fs.closeSync(fd);
  }
}

function looksBinary(file: string): boolean {
  try {
    return readHead(file, 8192).includes(0);
  } catch {
    return true;
  }
}

function looksSecret(file: string): boolean {
  let text: string;
  try {
    text = new TextDecoder("utf-8", { fatal: false, ignoreBOM: true })
      .decode(readHead(file, SCAN_BYTES))
      .replace(/\uFFFD/g, "");
  } catch {
    return true;
  }
  return SECRET_CONTENT.some((pattern) => pattern.test(text));
}

function ignoreFiles(project: string): string[] {
  return IGNORE_NAMES.map((name) => path.join(project, name)).filter((file) => isFile(file));
}

function rejectSecretContext(
  project: string,
  compiled: DockerIgnore,
  label: string,
  opts: { error?: "adopt" | "codegen"; suggestion?: string | null } = {},
): void {
  const leaked: string[] = [];
  for (const [current, dirnames, filenames] of osWalk(project)) {
    const kept = dirnames.filter((d) => !isSymlink(path.join(current, d)));
    dirnames.length = 0;
    dirnames.push(...kept);
    for (const filename of filenames) {
      if (!isSecretName(filename)) continue;
      const relative = rel(project, path.join(current, filename));
      if (!compiled.excludes(relative)) leaked.push(relative);
    }
  }
  if (leaked.length === 0) return;
  const sample = leaked.slice(0, 8).join(", ");
  const message =
    `${label} does not exclude secret-named file(s): ${sample}. ` +
    "Add ignore lines such as `**/.env`, `**/*.pem`, `**/id_rsa*`, " +
    "`**/*.tfstate` (a bare `.env` only matches the directory root, and " +
    "a later `!` line can re-include a file).";
  if ((opts.error ?? "adopt") === "adopt") throw new AdoptRejectedError(message, { usage: false });
  throw new AICodegenError(message, { suggestion: opts.suggestion ?? undefined });
}

function rejectWheelExclusion(
  compiled: DockerIgnore,
  label: string,
  opts: { error?: "adopt" | "codegen"; suggestion?: string | null } = {},
): void {
  if (!compiled.excludes(WHEEL_PROBE)) return;
  const message =
    `${label} excludes *.whl, so ABX_SERVER_SDK_SOURCE cannot inject a local server wheel. ` +
    "Remove the *.whl rule when you need that override.";
  if ((opts.error ?? "adopt") === "adopt") throw new AdoptRejectedError(message, { usage: false });
  throw new AICodegenError(message, { suggestion: opts.suggestion ?? undefined });
}

const EXPOSE_RE = new RegExp(`(?:^|\\n)${"[" + PY_WHITESPACE + "]"}*EXPOSE${"[" + PY_WHITESPACE + "]"}+([^\\n]+)`, "gi");

/** Python `str.isdigit()` restricted to decimal digits (`Nd`), whose `int()` value is well defined. */
function decimalDigitValue(ch: string): number | null {
  if (!/^\p{Nd}$/u.test(ch)) return null;
  let start = ch.codePointAt(0) as number;
  while (start > 0 && /^\p{Nd}$/u.test(String.fromCodePoint(start - 1))) start -= 1;
  return ((ch.codePointAt(0) as number) - start) % 10;
}

function parseDecimal(token: string): number | null {
  const chars = [...token];
  if (chars.length === 0) return null;
  let value = 0;
  for (const ch of chars) {
    const digit = decimalDigitValue(ch);
    if (digit === null) return null;
    value = value * 10 + digit;
  }
  return value;
}

function exposedPorts(dockerfile: string): Set<number> {
  const found = new Set<number>();
  for (const match of dockerfile.matchAll(EXPOSE_RE)) {
    for (const token of pySplitWhitespace(match[1] as string)) {
      const number = (token.split("/", 1)[0] ?? "") as string;
      const value = parseDecimal(number);
      if (value !== null) found.add(value);
    }
  }
  return found;
}

class PyValueError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "ValueError";
  }
}

function checkPorts(dockerfile: string, commands: string, data: Record<string, unknown>, warnings: string[]): void {
  const raw = data["ports"];
  const ports = new Set<number>(Array.isArray(raw) ? raw.map((port) => Math.trunc(Number(port))) : []);
  const exposed = exposedPorts(dockerfile);
  if (!ports.has(SERVER_PORT) || !exposed.has(SERVER_PORT)) {
    throw new AICodegenError(
      `template.yaml ports and Dockerfile EXPOSE must both include ${SERVER_PORT} ` + "(the SandboxServer port).",
      { suggestion: "Regenerate, or add the port to both files." },
    );
  }
  const others = [...ports].filter((port) => port !== SERVER_PORT).sort((a, b) => a - b);
  for (const port of others) {
    if (!exposed.has(port)) warnings.push(`Port ${port} is in template.yaml but not EXPOSE.`);
  }
  if (others.length > 0 && !commands.includes("subprocess")) {
    warnings.push(
      "template.yaml declares a port besides " +
        `${SERVER_PORT}, but commands.py never starts a subprocess. ` +
        "The project's own service is expected to be launched from commands.py.",
    );
  }
}

function planIgnores(project: string, generated: string | null): Array<[DockerIgnore, string]> {
  const found: Array<[DockerIgnore, string]> = ignoreFiles(project).map((file) => [
    DockerIgnore.fromFile(file),
    path.basename(file),
  ]);
  if (generated !== null) found.push([DockerIgnore.fromText(generated), ".dockerignore (generated)"]);
  return found;
}

function checkCopySources(
  project: string,
  dockerfile: string,
  files: Readonly<Record<string, string>>,
  ignores: ReadonlyArray<[DockerIgnore, string]>,
  hint: string,
  warnings: string[],
): void {
  for (const source of parseCopySources(dockerfile)) {
    if (source.kind === "variable") {
      warnings.push(`Dockerfile line ${source.line} copies ${pyRepr(source.source)}; build args are not checked.`);
      continue;
    }
    if (source.kind === "glob") {
      if (!source.source.endsWith("*.whl")) {
        warnings.push(
          `Dockerfile line ${source.line} copies glob ${pyRepr(source.source)}, which was not expanded.`,
        );
      }
      continue;
    }
    const relative = normaliseSource(source.source);
    if (relative === null) {
      throw new AICodegenError(
        `Dockerfile line ${source.line} copies ${pyRepr(source.source)}, which escapes the project.`,
        { suggestion: hint },
      );
    }
    if (Object.hasOwn(files, relative)) {
      if (ignores.some(([compiled]) => compiled.excludes(relative))) {
        throw new AICodegenError(
          `Dockerfile copies ${relative}, but an ignore file excludes it, so the ` +
            "build context would not contain it.",
          { suggestion: hint },
        );
      }
      continue;
    }
    const candidate = path.join(project, relative);
    if (isSymlink(candidate) || !(isFile(candidate) || isDir(candidate))) {
      throw new AICodegenError(
        `Dockerfile line ${source.line} copies ${pyRepr(relative)}, which is not in the project.`,
        { suggestion: hint },
      );
    }
    if (ignores.some(([compiled]) => compiled.excludes(relative))) {
      throw new AICodegenError(`Dockerfile copies ${relative}, but an ignore file excludes it.`, { suggestion: hint });
    }
  }
}

function normaliseSource(source: string): string | null {
  let text = pyStrip(source.replaceAll("\\", "/"));
  while (text.startsWith("./")) text = text.slice(2);
  text = text.replace(/\/+$/, "");
  if (!text || text.startsWith("/")) return null;
  const parts = text.split("/").filter((part) => part !== "" && part !== ".");
  if (parts.includes("..")) return null;
  return text;
}

function snapshot(root: string): Map<string, string> {
  const found = new Map<string, string>();
  for (const [current, dirnames, filenames] of osWalk(root)) {
    const kept = dirnames.filter((d) => !d.startsWith("."));
    dirnames.length = 0;
    dirnames.push(...kept);
    for (const name of filenames) {
      const file = path.join(current, name);
      if (isSymlink(file)) continue;
      try {
        found.set(rel(root, file), sha256(file));
      } catch {
        continue;
      }
    }
  }
  return found;
}

function notAppliedFiles(staged: StagedProject, taken: ReadonlySet<string>): string[] {
  const after = snapshot(staged.stagingDir);
  const changed: string[] = [];
  for (const [relative, digest] of after) {
    if (taken.has(relative)) continue;
    if (staged.manifest.get(relative) !== digest) changed.push(relative);
  }
  for (const relative of staged.manifest.keys()) {
    if (!after.has(relative) && !taken.has(relative)) changed.push(`${relative} (deleted)`);
  }
  return changed.sort(cmpCodePoint);
}

function assertReserved(relative: string): void {
  if (!RESERVED_FILES.includes(relative) || path.posix.basename(relative) !== relative) {
    throw new AICodegenError(`Refusing to write ${pyRepr(relative)}: not a reserved template file.`);
  }
}

function assertUnlinked(project: string, relative: string): void {
  let current = project;
  for (const part of relative.split("/").filter((p) => p !== "" && p !== ".")) {
    current = path.join(current, part);
    if (isSymlink(current)) {
      throw new AdoptRejectedError(
        `${relative} is a symlink (or sits under one); refusing to write through it.`,
        { usage: false },
      );
    }
  }
}

function backupPath(target: string): string {
  let candidate = `${target}.abx-bak`;
  let number = 1;
  while (pathExists(candidate) || isSymlink(candidate)) {
    candidate = `${target}.abx-bak.${number}`;
    number += 1;
  }
  return candidate;
}
