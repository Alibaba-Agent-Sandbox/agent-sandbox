/**
 * A compiled-pattern stand-in carrying Python's `re.Pattern.pattern` text. Python's `$` also matches before one
 * trailing newline, so `NAME_PATTERN.match("abc\n")` succeeds there and does here.
 */
export class PyPattern {
  readonly pattern: string;
  private readonly re: RegExp;

  constructor(pattern: string, jsSource: string) {
    this.pattern = pattern;
    this.re = new RegExp(jsSource);
  }

  match(text: string): boolean {
    return this.re.test(text);
  }

  test(text: string): boolean {
    return this.match(text);
  }
}

