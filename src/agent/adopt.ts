/**
 * Return `name` when it matches {@link NAME_PATTERN}.
 *
 * The length cap is a CLI safety limit, not a claimed platform limit (that constraint is still unconfirmed).
 *
 * Throws `AdoptRejectedError` when `name` is empty, too long, or has other characters.
 */
export function validateTemplateName(name: string): string {
  if (!name || !NAME_PATTERN.match(name) || [...name].length > NAME_MAX) {
    throw new AdoptRejectedError(
      `Template name ${pyRepr(name)} must match ${NAME_PATTERN.pattern} and be at most ${NAME_MAX} characters. Pass --name.`,
      { usage: true },
    );
  }
  return name;
}

/** Slug of the directory name, or a usage error when there is no ASCII slug. */
export function defaultTemplateName(project: string): string {
  const normalised = pyPathStr(project);
  const base = normalised === "." ? "" : path.basename(normalised);
  let slug = stripChars(base.toLowerCase().replace(/[^a-z0-9]+/g, "-"), "-");
  slug = stripChars(cpSlice(slug, 0, 64), "-");
  if (!slug) {
    throw new AdoptRejectedError(
      `Cannot derive a template name from directory ${pyRepr(base)}. ` +
        "Pass --name (lowercase letters, digits and hyphens).",
      { usage: true },
    );
  }
  return validateTemplateName(slug);
}

function resolvePath(p: string): string {
  try {
    return fs.realpathSync.native(p);
  } catch {
    return path.resolve(p);
  }
}

/**
 * Resolve `project` and reject roots, the home directory and `~/.abx`.
 *
 * Throws `AdoptRejectedError` when the path is missing or not a safe project directory.
 */
export function assertAdoptable(project: string): string {
  if (!isDir(project)) {
    throw new AdoptRejectedError(
      `'${pyPathStr(project)}' is not an existing directory. With --adopt the argument is ` +
        "the project directory (default: .). Put extra instructions in --hint.",
      { usage: true },
    );
  }
  const resolved = resolvePath(project);
  if (resolved === path.parse(resolved).root) {
    throw new AdoptRejectedError(`Refusing to adopt the filesystem root ${resolved}.`, { usage: true });
  }
  const home = resolvePath(homeDir());
  if (resolved === home) {
    throw new AdoptRejectedError(`Refusing to adopt the home directory ${resolved}.`, { usage: true });
  }
  const abx = resolvePath(path.join(home, ".abx"));
  if (resolved === abx || isRelativeTo(resolved, abx)) {
    throw new AdoptRejectedError(
      `Refusing to adopt ${resolved}: it is inside ~/.abx, which holds credentials.`,
      { usage: true },
    );
  }
  return resolved;
}

/**
 * Apply the reserved-file policy and the secret-in-context check.
 *
 * `needsConfirm` is true on an interactive terminal without `--yes`: an existing Dockerfile (or our own
 * `commands.py`) can wait for the preview. Everywhere else, replacing an existing file needs `--force`.
 *
 * Throws `AdoptRejectedError` on policy or secret-context violations. No model call yet.
 */
export function preflight(project: string, opts: { force: boolean; needsConfirm: boolean }): Preflight {
  const { force, needsConfirm } = opts;
  const shown = pyPathStr(project);
  const hashes: Record<string, string | null> = {};
  for (const name of RESERVED_FILES) {
    const file = path.join(project, name);
    if (isSymlink(file)) {
      throw new AdoptRejectedError(`${name} is a symlink; refusing to follow or replace it.`, { usage: false });
    }
    if (pathExists(file) && !isFile(file)) {
      throw new AdoptRejectedError(`${name} exists and is not a regular file.`, { usage: false });
    }
    hashes[name] = isFile(file) ? sha256(file) : null;
  }

  if (hashes["template.yaml"] !== null && !force) {
    throw new AdoptRejectedError(
      `${shown} already has template.yaml, so it is a template. ` +
        `Run 'abx deploy ${shown}'. Pass --force to regenerate ` +
        "(the original is kept as template.yaml.abx-bak).",
      { usage: false },
    );
  }

  const commands = path.join(project, "commands.py");
  let userOwned = false;
  if (hashes["commands.py"] !== null) {
    const text = readTextReplace(commands);
    userOwned = !text.includes("agent_sandbox.server");
    if (userOwned && !force) {
      throw new AdoptRejectedError(
        "commands.py exists and is not an Agent Sandbox server entry point. " +
          "Pass --force to replace it (the original is kept as commands.py.abx-bak).",
        { usage: false },
      );
    }
  }

  const replacing = ["Dockerfile", "commands.py"].filter(
    (name) => hashes[name] !== null && !(name === "commands.py" && userOwned),
  );
  if (replacing.length > 0 && !needsConfirm && !force) {
    const listed = replacing.join(", ");
    throw new AdoptRejectedError(
      `Refusing to replace ${listed} without a preview. ` +
        "Re-run in a terminal to confirm the diff, or pass --force.",
      { usage: true },
    );
  }

  for (const file of ignoreFiles(project)) {
    const compiled = DockerIgnore.fromFile(file);
    rejectSecretContext(project, compiled, path.basename(file));
    rejectWheelExclusion(compiled, path.basename(file));
  }
  return new Preflight(hashes);
}

/**
 * Copy candidate files into a fresh staging directory.
 *
 * The copy lives under the system temp dir (mode 0700), never under `~/.abx`. Secret-named files, secret-looking
 * files, symlinks, binaries and files over {@link MAX_FILE_BYTES} are left out and reported.
 *
 * Throws `AdoptRejectedError` when the project exceeds the file or byte budget.
 */
export function stageProject(project: string, opts: { stagingRoot?: string | null } = {}): StagedProject {
  const ignores = ignoreFiles(project).map((file) => DockerIgnore.fromFile(file));
  const copied: Array<[string, string, number]> = [];
  const excluded: Record<string, string[]> = {};
  let total = 0;

  for (const [current, dirnames, filenames] of osWalk(project)) {
    const kept: string[] = [];
    for (const dirname of dirnames) {
      const child = path.join(current, dirname);
      if (SKIP_DIRS.has(dirname)) {
        exclude(excluded, "directory", rel(project, child));
        continue;
      }
      if (isSymlink(child)) {
        exclude(excluded, "symlink", rel(project, child));
        continue;
      }
      kept.push(dirname);
    }
    dirnames.length = 0;
    dirnames.push(...kept);

    for (const filename of filenames) {
      const file = path.join(current, filename);
      const relative = rel(project, file);
      if (isSymlink(file)) {
        exclude(excluded, "symlink", relative);
        continue;
      }
      let size: number;
      try {
        size = fs.statSync(file).size;
      } catch {
        exclude(excluded, "unreadable", relative);
        continue;
      }
      if (ignores.some((rule) => rule.excludes(relative))) {
        exclude(excluded, "ignored", relative);
        continue;
      }
      if (isSecretName(filename)) {
        exclude(excluded, "secret-name", relative);
        continue;
      }
      if (size > seams.MAX_FILE_BYTES) {
        exclude(excluded, "too-large", relative);
        continue;
      }
      if (looksBinary(file)) {
        exclude(excluded, "binary", relative);
        continue;
      }
      if (looksSecret(file)) {
        exclude(excluded, "secret-content", relative);
        continue;
      }
      copied.push([relative, file, size]);
      total += size;
    }
  }

  if (copied.length > seams.MAX_FILES || total > seams.MAX_BYTES) {
    throw new AdoptRejectedError(
      `Project has ${copied.length} candidate files (${total} bytes); the limit is ` +
        `${seams.MAX_FILES} files and ${seams.MAX_BYTES} bytes. Point --adopt at a subdirectory, ` +
        "or add a .dockerignore.",
      { usage: true },
    );
  }

  let staging: string;
  if (opts.stagingRoot === undefined || opts.stagingRoot === null) {
    staging = fs.mkdtempSync(path.join(os.tmpdir(), `abx-adopt-${process.pid}`));
  } else {
    fs.mkdirSync(opts.stagingRoot, { recursive: true });
    staging = fs.mkdtempSync(path.join(opts.stagingRoot, `abx-adopt-${process.pid}`));
  }

  const manifest = new Map<string, string>();
  try {
    for (const [relative, file] of copied) {
      const dest = path.join(staging, relative);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      const data = fs.readFileSync(file);
      fs.writeFileSync(dest, data);
      manifest.set(relative, createHash("sha256").update(data).digest("hex"));
    }
  } catch (exc) {
    fs.rmSync(staging, { recursive: true, force: true });
    throw exc;
  }

  return new StagedProject({
    stagingDir: staging,
    manifest,
    copied: copied.map(([relative]) => relative),
    excluded: Object.fromEntries(Object.entries(excluded).map(([key, values]) => [key, [...values]])),
    totalBytes: total,
  });
}

