/** Prompt for the adopt run. Paths are workspace-relative; no absolute paths. */
export function buildAdoptPrompt(
  staged: StagedProject,
  opts: { hint: string | null | undefined; templateName: string; existing: readonly string[] },
): string {
  const firstChunk = staged.copied.slice(0, 200);
  let listing = firstChunk.map((p) => `- ${p}`).join("\n");
  if (staged.copied.length > 200) listing += `\n- … and ${staged.copied.length - 200} more`;
  const present = opts.existing.length > 0 ? opts.existing.join(", ") : "(none)";
  const extra = opts.hint ? pyStrip(opts.hint) : "(none)";
  const guide = buildTemplateGuide("adopt");
  return adoptPromptTemplate({
    template_name: opts.templateName,
    extra,
    present,
    listing: listing || "(empty)",
    guide,
  });
}

/**
 * Validate the agent's output and return the bytes that may be written.
 *
 * Reads each reserved file once. A symlink, a missing file or a failed check raises `AICodegenError` and writes
 * nothing.
 *
 * Throws `AICodegenError` when the staged result is not a valid template.
 */
export function planFromStaging(
  project: string,
  staged: StagedProject,
  opts: { templateName: string; rawOutput: string },
): AdoptPlan {
  const hint = `Inspect the staging directory: ${staged.stagingDir}`;
  const contents: Record<string, string> = {};
  for (const name of AGENT_FILES) {
    const file = path.join(staged.stagingDir, name);
    if (isSymlink(file) || !isFile(file)) {
      throw new AICodegenError(`Staged ${name} is missing or is a symlink.`, { suggestion: hint });
    }
    contents[name] = readTextReplace(file);
  }

  const data = codegen.validateTemplateWorkspace(staged.stagingDir, opts.templateName, { retry: hint });
  contents["template.yaml"] = dumpYaml(data);

  const warnings: string[] = [];
  checkPorts(contents["Dockerfile"] as string, contents["commands.py"] as string, data, warnings);

  const generateIgnore = isFile(path.join(project, ".dockerignore")) === false;
  if (generateIgnore) contents[".dockerignore"] = GENERATED_DOCKERIGNORE;
  const ignores = planIgnores(project, contents[".dockerignore"] ?? null);
  checkCopySources(project, contents["Dockerfile"] as string, contents, ignores, hint, warnings);
  for (const [compiled, label] of ignores) {
    rejectSecretContext(project, compiled, label, { error: "codegen", suggestion: hint });
    rejectWheelExclusion(compiled, label, { error: "codegen", suggestion: hint });
  }

  const taken = new Set(generateIgnore ? Object.keys(contents) : AGENT_FILES);
  const notApplied = notAppliedFiles(staged, taken);
  const replaces = Object.keys(contents).filter((name) => isFile(path.join(project, name)));
  return new AdoptPlan({
    templateName: opts.templateName,
    files: contents,
    replaces,
    notApplied,
    warnings,
    rawOutput: opts.rawOutput,
  });
}

/**
 * Write `plan` into `project`. Replaced files get a never-overwritten backup.
 *
 * Every target is re-checked against {@link Preflight} immediately before writing, and a symlink anywhere on the
 * target path aborts with nothing written. A failure mid-write restores the backups already made.
 *
 * Throws `AdoptRejectedError` on drift or a symlink (the project is left unchanged) and `AICodegenError` when a path
 * escapes the project.
 */
export function promote(project: string, plan: AdoptPlan, state: Preflight): PromoteResult {
  for (const relative of Object.keys(plan.files)) {
    assertReserved(relative);
    assertUnlinked(project, relative);
    const current = path.join(project, relative);
    const expected = Object.hasOwn(state.hashes, relative) ? (state.hashes[relative] ?? null) : null;
    if (isSymlink(current)) {
      throw new AdoptRejectedError(`${relative} became a symlink; refusing to write.`, { usage: false });
    }
    const actual = isFile(current) ? sha256(current) : null;
    if (actual !== expected) {
      throw new AdoptRejectedError(
        `${relative} changed while the agent was running; refusing to write. Nothing was modified.`,
        { usage: false },
      );
    }
  }

  const backups: Array<[string, string]> = [];
  const created: string[] = [];
  const written: string[] = [];
  try {
    for (const [relative, content] of Object.entries(plan.files)) {
      const target = path.join(project, relative);
      const existed = isFile(target);
      if (existed) {
        const backup = backupPath(target);
        fs.renameSync(target, backup);
        backups.push([target, backup]);
      }
      const temporary = `${target}.abx-tmp`;
      seams.writeText(temporary, content);
      fs.renameSync(temporary, target);
      if (!existed) created.push(target);
      written.push(relative);
    }
  } catch (exc) {
    for (const [original, backup] of [...backups].reverse()) {
      unlinkIfExists(`${original}.abx-tmp`);
      if (pathExists(original) || isSymlink(original)) fs.unlinkSync(original);
      fs.renameSync(backup, original);
    }
    for (const file of created) unlinkIfExists(file);
    throw exc;
  }
  return new PromoteResult({ written, backedUp: backups.map(([, backup]) => path.basename(backup)) });
}

