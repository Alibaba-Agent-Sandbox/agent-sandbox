/**
 * A problem found before any model call.
 *
 * `usage` is true for mistakes in the invocation (the CLI raises a usage error) and false for conflicts with files
 * that already exist (a plain `ClickException`-style error, same as `template init` today).
 */
export class AdoptRejectedError extends Error {
  readonly usage: boolean;

  constructor(message: string, opts: { usage: boolean }) {
    super(message);
    this.name = "AdoptRejectedError";
    this.usage = opts.usage;
  }
}

